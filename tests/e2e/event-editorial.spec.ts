import { expect, test } from "@playwright/test";
test("month view preserves filters and manual intake handles errors", async ({ page }) => {
  await page.route("**/*", route => ["127.0.0.1", "localhost"].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/en/events?period=custom&from=2026-11-01&to=2026-11-30&location=monaco");
  await page.getByRole("button", { name: "Month", exact: true }).click();
  await expect(page.locator(".fc-daygrid")).toBeVisible();
  await expect(page.locator('.fc-event[href*="jimmy-gnecco"]')).toBeVisible();
  await expect(page.locator('.fc-event[href*="st-johns"]')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(await page.locator(".events-month").evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.getByRole("button", { name: "List", exact: true }).click();
  await expect(page).toHaveURL(/location=monaco/);
  const panel = page.locator("#suggest-event");
  await panel.locator("summary").click();
  await panel.getByRole("combobox").selectOption("correction");
  await panel.getByLabel("Name", { exact: true }).fill("TEST ONLY");
  await panel.getByLabel("Email", { exact: true }).fill("editor@example.com");
  await panel.getByLabel("Page to correct", { exact: false }).fill("https://azurmenton.com/en/events");
  await panel.getByLabel("Details", { exact: true }).fill("TEST ONLY: information for review");
  await panel.getByRole("checkbox").check();
  let requestBody: Record<string, unknown> = {};
  await page.route("**/api/editorial-submission", async route => { requestBody = route.request().postDataJSON(); await route.fulfill({ status: 502, json: { ok: false } }); });
  await panel.getByRole("button", { name: "Send for review" }).click();
  await expect(panel.getByRole("alert")).toBeVisible();
  await page.route("**/api/editorial-submission", route => route.fulfill({ json: { ok: true } }));
  await panel.getByRole("button", { name: "Send for review" }).click();
  await expect(panel.getByRole("status")).toContainText("manual review");
  expect(requestBody.type).toBe("correction");
  expect(errors).toEqual([]);
});
